#!/usr/bin/env node
/**
 * Is a creator's GMV for a brand and month worked out right, the same way in the
 * browser and in the database, and does a frozen month stay frozen?
 *
 * Needs nothing but this repository: the real migration
 * (supabase/migrations/20261105085000_collab_month_gmv_snapshots.sql) is run in
 * PGlite (Postgres compiled to WebAssembly) against a copy of the one table it
 * reads, and the browser calculation (src/lib/admin/month-gmv.ts) is imported
 * as it is. Four parts:
 *
 *   1. the rules, on cases built by hand, one rule at a time;
 *   2. the SQL and the browser code on the SAME rows, hand-built and 400 randomly
 *      generated, which must give the same answer to the cent;
 *   3. FREEZING: a closed month is written once, never changes after, a month
 *      that has not ended is refused, and the nightly job repairs a missed night;
 *   4. the month helpers the Creators table uses to decide when a frozen figure
 *      applies (leap years included).
 *
 * Run: pnpm verify:month-gmv
 */
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import {
  creatorBrandGmv,
  gmvKey,
  monthHasEnded,
  personKey,
  wholeMonthOf,
} from '../../../src/lib/admin/month-gmv.ts';

/* the month figure was first built as "posted in the month", then corrected to "so far":
   the second migration replaces the calculation, so a database gets both, in order */
const MIGRATION = ['20261105085000_collab_month_gmv_snapshots.sql', '20261106000000_collab_gmv_cumulative.sql']
  .map((f) => fs.readFileSync(new URL('../../../supabase/migrations/' + f, import.meta.url), 'utf8'))
  .join('\n;\n');

let failed = 0;
let passed = 0;
const ok = (cond, name, extra = '') => {
  if (cond) {
    passed += 1;
    console.log('  ok   ' + name);
  } else {
    failed += 1;
    console.log('  FAIL ' + name + (extra ? '  -> ' + extra : ''));
  }
};
const section = (s) => console.log('\n' + s);

/* ── a database that has the one table the migration reads ─────────────────── */
async function freshDb() {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema wurxbase;
    create table wurxbase.creators (
      id bigint generated by default as identity primary key,
      brand text, name text, video_codes jsonb
    );
    create function public.is_collabs_viewer() returns boolean language sql as 'select true';
    -- pg_cron is not here: enough of it for the migration to schedule itself
    create schema cron;
    create table cron.job (jobid serial primary key, jobname text, schedule text, command text);
    create function cron.schedule(n text, s text, c text) returns bigint language sql as
      'insert into cron.job (jobname, schedule, command) values (n, s, c) returning jobid::bigint';
    create function cron.unschedule(n text) returns boolean language sql as
      'delete from cron.job where jobname = n returning true';
  `);
  await db.exec(MIGRATION);
  return db;
}
const insertRows = async (db, rows) => {
  for (const r of rows) {
    await db.query('insert into wurxbase.creators (brand, name, video_codes) values ($1, $2, $3::jsonb)', [
      r.brand,
      r.name,
      r.video_codes == null ? null : JSON.stringify(r.video_codes),
    ]);
  }
};
const sqlMonth = async (db, month) => {
  const r = await db.query('select * from public.collab_month_gmv($1)', [month]);
  const m = new Map();
  for (const x of r.rows) {
    m.set(gmvKey(x.brand, x.creator_key), {
      brand: x.brand, creatorKey: x.creator_key, creatorName: x.creator_name,
      videos: x.videos, withSales: x.videos_with_sales, zero: x.videos_zero,
      unsynced: x.videos_unsynced, gmv: Number(x.gmv),
      periodVideos: x.month_videos, periodGmv: Number(x.month_gmv),
    });
  }
  return m;
};
const jsMonth = (rows, month) => creatorBrandGmv(rows, { from: `${month}-01`, to: `${month}-31` });
const vid = (id, who = 'x') => `https://www.tiktok.com/@${who}/video/${id}`;
const v = (id, date, revenue, extra = {}) => ({ video: vid(id), date, ...(revenue === undefined ? {} : { revenue }), ...extra });
const one = (m, brand, name) => m.get(gmvKey(brand, name));

