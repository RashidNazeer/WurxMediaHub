section('2. THE DATABASE AND THE BROWSER AGREE, to the cent');
const same = (a, b) => {
  if (a.size !== b.size) return `${a.size} entries vs ${b.size}`;
  for (const [k, x] of a) {
    const y = b.get(k);
    if (!y) return `missing ${JSON.stringify(k)}`;
    for (const f of ['videos', 'withSales', 'zero', 'unsynced', 'creatorName', 'periodVideos']) if (x[f] !== y[f]) return `${JSON.stringify(k)} ${f}: ${x[f]} vs ${y[f]}`;
    for (const f of ['gmv', 'periodGmv']) if (Math.abs(x[f] - y[f]) > 0.005) return `${JSON.stringify(k)} ${f}: ${x[f]} vs ${y[f]}`;
  }
  return '';
};

/* a deterministic random source, so a failure can be reproduced */
let seed = 20261105;
const rnd = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; };
const pick = (a) => a[Math.floor(rnd() * a.length)];
function randomRows(n) {
  const brands = ['Aqua', ' Aqua', 'Zest', 'Penetrex '];
  const names = ['Ann Lee', ' ann lee', 'ANN LEE', 'Bo Chan', 'bo chan ', 'Cy Dunn', 'Di Fox', 'Ed Gray'];
  const pool = Array.from({ length: 60 }, (_, i) => 7000000000000000 + i * 7919);
  const days = ['2026-09-30', '2026-10-01', '2026-10-15', '2026-10-31', '2026-11-01', '2026-08-12', '', undefined];
  const rows = [];
  for (let i = 0; i < n; i++) {
    const vids = [];
    for (let k = Math.floor(rnd() * 9); k > 0; k--) {
      const id = pick(pool);
      const url = rnd() < 0.08 ? `https://vm.tiktok.com/ZS${id % 977}/` : rnd() < 0.2 ? `${vid(id)}?lang=en` : vid(id);
      const day = pick(days);
      const rv = rnd();
      const e = { video: url, ...(day === undefined ? {} : { date: day }) };
      if (rv < 0.12) { /* no revenue field at all */ }
      else if (rv < 0.2) e.revenue = null;
      else if (rv < 0.45) e.revenue = 0;
      else if (rv < 0.5) e.revenue = String((rnd() * 400).toFixed(2));
      else if (rv < 0.53) e.revenue = -Math.round(rnd() * 50);
      else e.revenue = Math.round(rnd() * 40000) / 100;
      vids.push(e);
    }
    rows.push({ brand: pick(brands), name: pick(names), video_codes: rnd() < 0.05 ? null : vids });
  }
  return rows;
}
{
  const fixed = [
    { brand: 'Aqua', name: 'Ann Lee', video_codes: [v(1001, '2026-10-03', 100), v(1002, '2026-10-20', 50.5), v(1003, '2026-09-30', 999)] },
    { brand: 'Aqua', name: ' ann lee ', video_codes: [v(1004, '2026-10-08', 25), v(1001, '2026-10-03', 140)] },
    { brand: 'Aqua', name: 'Bo Chan', video_codes: [v(3001, '2026-10-02', 0), v(3002, '2026-10-04'), v(3003, '', 500)] },
    { brand: 'Aqua', name: 'Cy Dunn', video_codes: [v(4001, '2026-10-09', '12.50'), v(4002, '2026-10-10', -7)] },
    { brand: 'Aqua', name: 'No Videos', video_codes: [] },
    { brand: 'Aqua', name: 'Null Videos', video_codes: null },
  ];
  const db = await freshDb();
  await insertRows(db, fixed);
  ok(same(jsMonth(fixed, '2026-10'), await sqlMonth(db, '2026-10')) === '', 'hand-built rows: the same answer from SQL and from the browser', same(jsMonth(fixed, '2026-10'), await sqlMonth(db, '2026-10')));
  await db.close();
}
{
  const rows = randomRows(400);
  const db = await freshDb();
  await insertRows(db, rows);
  for (const month of ['2026-10', '2026-09', '2026-08', '2026-11']) {
    const a = jsMonth(rows, month);
    const b = await sqlMonth(db, month);
    const diff = same(a, b);
    ok(diff === '', `400 random creators, ${month}: SQL and browser agree (${a.size} creator-brand totals)`, diff);
  }
  await db.close();
}

