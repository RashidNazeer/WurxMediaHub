section('4. THE MONTH HELPERS the Creators table uses');
ok(wholeMonthOf({ from: '2026-10-01', to: '2026-10-31' }) === '2026-10', 'Oct 1 to Oct 31 is the whole of 2026-10');
ok(wholeMonthOf({ from: '2026-11-01', to: '2026-11-30' }) === '2026-11', 'a 30-day month ends on the 30th');
ok(wholeMonthOf({ from: '2026-02-01', to: '2026-02-28' }) === '2026-02', 'February 2026 ends on the 28th');
ok(wholeMonthOf({ from: '2028-02-01', to: '2028-02-29' }) === '2028-02', 'February 2028 (a leap year) ends on the 29th');
